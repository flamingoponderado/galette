(** * HOL4 L3 ARMv8 model [arm8] (generated by L3)

    Port of [HOL/examples/l3-machine-code/arm8/model/arm8Script.sml], which
    is itself generated by L3 through the [Import] library
    ([HOL/examples/l3-machine-code/common/Import.sml]).  This file is
    produced mechanically from the HOL definitions of [arm8Theory] (by
    [scripts/l3-to-rocq/], which prints each defining theorem of the HOL
    theory as Rocq), followed by hand edits that are listed below.  The
    translation is:

    - An L3 [Construct] (a HOL datatype) is an [Inductive] with HOL's
      constructors in HOL's order; L3's width-specialised constructor names
      such as [AddSubImmediate@64] are not Rocq identifiers and become
      [AddSubImmediate_64].  An L3 [Record] is a Rocq [Record] whose fields
      carry the names of HOL's accessor constants [t_f] (e.g.
      [arm8_state_PC]), in HOL's field order; [s with f := v] is HOL's
      [t_f_fupd (K v) s], written [t_f_fupd (fun _ => v) s].  HOL type names
      that are also constructor names ([Data], [Branch], [LoadStore], ...)
      get the suffix [_ty].
    - HOL pairs are right-nested ([a # b # c] is [a # (b # c)]) and so are
      the Rocq ones here: [a * (b * c)], written [(x, (y, z))].  [FST] and
      [SND] are [fst] and [snd].  The exception is [state_transformer]'s
      [FOR (i, j, a)], whose argument is Galette's left-nested triple (as in
      the RISC-V model).
    - [FTy n] is [word n].  Definitions that L3 makes polymorphic in a word
      width ['N] take an implicit width [{Nw : N}]; uses give the instance
      by name ([X (Nw:=64)]).  Applications of library word operations whose
      result width the arguments do not determine ([n2w], [w2w], [sw2sw],
      [v2w], extracts and concatenations, ...) are ascribed their HOL type.
    - [case] is a [match] with HOL's first-match semantics; a [case] on
      literal patterns (words, numbers) is an [if] chain on [bool_decide]
      equalities, as HOL's [literal_case].  HOL's [=] is [bool_decide], and
      [x IN {a; b}] is [bool_decide (x IN (a INSERT (b INSERT {})))].
    - [num] operations are [N]'s; [int] operations are written with [Z.]
      functions, [&n] is [Z.of_N n] and HOL's [Num] is [Z.to_N].

    The datatypes carry no [HOL] tags (the L3 declaration forms are not
    recognised by [scripts/check-hol-refs.py]); each says which HOL type it
    is.  Every [Def]/[Def0] below is tagged with its [_def].  The auxiliary
    functions that HOL generates outside the script (record field updates
    [t_f_fupd], enumeration maps [t2num]/[num2t]) are untagged Galette
    definitions with HOL's names.

    Hand edits: the recursive [ByteList], [Poly32Mod2_loop] and
    [CountTrailing] are defined by well-founded recursion (or a fuel that
    is provably sufficient) and HOL's equations are the tagged [_def]
    theorems. *)

