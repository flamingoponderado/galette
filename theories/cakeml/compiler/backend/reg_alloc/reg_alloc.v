}.

(** Generated by HOL's [define_run] (HOL's [run_ira_state_def]). *)
(*! HOL "cakeml/compiler/backend/reg_alloc/reg_allocScript.sml" "run_ira_state_def" *)
Definition run_ira_state {A E} (x : M ra_state A E) (state : ira_state) : exc A E :=
  run x (mk_ra_state
    (marray_replicate (FST state.(ira_state_adj_ls)) (SND state.(ira_state_adj_ls)))
    (marray_replicate (FST state.(ira_state_node_tag)) (SND state.(ira_state_node_tag)))
    (marray_replicate (FST state.(ira_state_degrees)) (SND state.(ira_state_degrees)))
    state.(ira_state_dim)
    state.(ira_state_simp_wl)
    state.(ira_state_spill_wl)
    state.(ira_state_freeze_wl)
    state.(ira_state_avail_moves_wl)
    state.(ira_state_unavail_moves_wl)
    (marray_replicate (FST state.(ira_state_coalesced)) (SND state.(ira_state_coalesced)))
    (marray_replicate (FST state.(ira_state_move_related)) (SND state.(ira_state_move_related)))
    state.(ira_state_stack)).

(*! HOL "cakeml/compiler/backend/reg_alloc/reg_allocScript.sml" "reg_alloc_aux_def" *)
Definition reg_alloc_aux (alg : algorithm) (scost : option (num_map N)) (k : N)
    (moves : list (N * (N * N))) (ct : clash_tree) (forced : list (N * N)) (fs : num_set)
    (tfn : num_map N * (num_map N * N)) : exc (num_map N) state_exn :=
  let '(ta, (fa, n)) := tfn in
  run_ira_state (do_reg_alloc alg scost k moves ct forced fs (ta, (fa, n)))
    {| ira_state_adj_ls := (n, []);
       ira_state_node_tag := (n, Atemp);
       ira_state_degrees := (n, 0);
       ira_state_dim := n;
       ira_state_simp_wl := [];
       ira_state_spill_wl := [];
       ira_state_freeze_wl := [];
       ira_state_avail_moves_wl := [];
       ira_state_unavail_moves_wl := [];
       ira_state_coalesced := (n, 0);
       ira_state_move_related := (n, false);
       ira_state_stack := [] |}.

(*! HOL "cakeml/compiler/backend/reg_alloc/reg_allocScript.sml" "reg_alloc_def" *)
Definition reg_alloc (alg : algorithm) (scost : option (num_map N)) (k : N)
    (moves : list (N * (N * N))) (ct : clash_tree) (forced : list (N * N)) (fs : num_set)
    : exc (num_map N) state_exn :=
  reg_alloc_aux alg scost k moves ct forced fs (mk_bij ct).
