(** ** Tags and the allocator state *)

(*! HOL "cakeml/compiler/backend/reg_alloc/reg_allocScript.sml" "tag" *)
Inductive tag : Type :=
| Fixed : N -> tag
| Atemp : tag
| Stemp : tag.

#[global] Instance tag_eq_dec : EqDecision tag.
Proof.
  intros [m| |] [n| |]; try (right; discriminate); try (left; reflexivity).
  destruct (decide (m = n)) as [->|ne]; [left; reflexivity|right; congruence].
Defined.

#[global] Instance tag_inhabited : Inhabited tag := Atemp.

