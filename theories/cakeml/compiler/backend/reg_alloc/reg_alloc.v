(** * CakeML [reg_alloc]: the monadic graph-colouring register allocator

    A port of [compiler/backend/reg_alloc/reg_allocScript.sml] (definitions
    only; the theorem [convention_partitions] is not ported yet).

    The allocator runs in the state-exception monad of [ml_monadBase]
    ([M ra_state A state_exn], abbreviated [RA A]).  HOL generates a number of
    functions with ML code rather than [Definition]s; they are written out
    here by hand with HOL's names and HOL's exact definitions, and are not
    tagged (there is no HOL declaration to cite):
    - [define_monad_access_funs ``:ra_state``]: [get_f]/[set_f] for every
      field [f] ([get_f = \state. (M_success state.f, state)],
      [set_f x = \state. (M_success (), state with f := x)]);
    - [define_monad_exception_functions ``:state_exn`` ``:ra_state``]:
      [raise_Fail], [raise_Subscript], [handle_Fail], [handle_Subscript];
    - [define_MFarray_manip_funs] for the fixed-size arrays [adj_ls],
      [node_tag], [degrees], [coalesced], [move_related]: [f_length]
      ([Marray_length]), [f_sub] ([Marray_sub] raising [Subscript]) and
      [update_f] ([Marray_update] raising [Subscript]);
    - [define_run ``:ra_state`` [...] "ira_state"]: the record [ira_state]
      (array fields replaced by [(size, initial value)] pairs; its field
      names are prefixed with [ira_state_] because Rocq record fields share
      the module namespace with [ra_state]'s) and [run_ira_state].

    The arrays are HOL lists, accessed and updated in linear time
    ([Msub]/[Mupdate]); this is HOL's semantics (out-of-bounds accesses raise
    [Subscript]).

    Naming: HOL's [clash_tree] constructor [Set] is [Set_] ([Set] is a Rocq
    keyword).  [coalesce_parent] and [coalesce_root] recurse on a smaller
    node index ([xt < x]); they are defined with [Fix] on [<] over [N] and
    HOL's equations are the tagged [_def] theorems.  [rpt_do_step] recurses
    on [SUC c] and uses [num_rec].  [lookup_any] ([miscScript]) is not in
    [misc.v] yet and is defined locally (untagged). *)

