Ltac eval_closed_word t :=
  let c := eval vm_compute in (w2n t) in change t with (n2w c : word64).

Ltac upd_eval b :=
  repeat match goal with
  | |- context [word_add (word_add b (n2w ?j)) (n2w ?k)] => rewrite (add_n2w_add b j k)
  | |- context [UPDATE (word_add b (n2w ?j)) ?v ?f (word_add b (n2w ?t))] =>
      rewrite (UPDATE_add_add b j t v f) by (vm_compute; reflexivity)
  | |- context [UPDATE b ?v ?f (word_add b (n2w ?t))] =>
      rewrite (UPDATE_b_add b t v f) by (vm_compute; reflexivity)
  | |- context [N.eqb ?x ?y] => closedB (N.eqb x y); let v := eval vm_compute in (N.eqb x y) in change (N.eqb x y) with v; cbv beta iota
  | |- context [@n2w ?a ?c] => tryif is_lit c then fail else idtac; closedN c; let v := eval vm_compute in c in change c with v
  end.

