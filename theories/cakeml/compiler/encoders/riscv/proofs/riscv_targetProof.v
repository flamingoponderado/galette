Lemma aexec_cong dom i A B :
  aregs A = aregs B -> apc A = apc B -> (forall a, dom a -> amem A a = amem B a) ->
  acc_ok dom i A ->
  aregs (aexec i A) = aregs (aexec i B) /\ apc (aexec i A) = apc (aexec i B) /\
  (forall a, dom a -> amem (aexec i A) a = amem (aexec i B) a).
Proof.
  destruct A as [gA pA mA], B as [gB pB mB]; cbn [aregs apc amem]; intros -> -> Hm Hacc.
  inst_cases' i; cbn [aexec acc_ok aregs apc amem] in *; (split; [|split]);
    first [ (erewrite aload_cong; [reflexivity|exact Hacc|exact Hm])
          | (intros a Ha; apply astore_cong with dom; assumption)
          | lazymatch goal with |- context [astore] => fail | |- context [aload] => fail | _ => exact Hm end
          | lazymatch goal with |- context [astore] => fail | |- context [aload] => fail | _ => reflexivity end ].
Qed.

Lemma aexec_out dom i A x : acc_ok dom i A -> ~ dom x -> amem (aexec i A) x = amem A x.
Proof.
  destruct A as [g pc m]; intros Hacc Hx.
  inst_cases' i; cbn [aexec acc_ok aregs apc amem] in *; try reflexivity;
    apply astore_out with dom; assumption.
Qed.

Lemma mem_ok_regs i A B : aregs A = aregs B -> mem_ok i A -> mem_ok i B.
Proof. destruct A, B; cbn; intros ->; auto. Qed.

Lemma acc_ok_regs dom i A B : aregs A = aregs B -> acc_ok dom i A -> acc_ok dom i B.
Proof. destruct A, B; cbn; intros ->; auto. Qed.

Lemma bytes_at_intro dom ms A i :
  rv_rel dom ms A -> bytes_in_memory (apc A) (riscv_encode i) (amem A) dom -> bytes_at ms (Encode i).
Proof.
  intros (_ & _ & Hpc & Hm) Hb. unfold riscv_encode in Hb; cbn [bytes_in_memory] in Hb.
  destruct Hb as (E0 & D0 & E1 & D1 & E2 & D2 & E3 & D3 & _).
  rewrite !add_n2w_add in *. cbn [N.add] in *.
  unfold bytes_at. rewrite Hpc. rewrite !Hm by assumption. auto.
Qed.

Lemma one_step dom ms A i :
  rv_rel dom ms A -> step_pre dom A i ->
  rv_rel dom (riscv_next ms) (aexec i A) /\
  (forall x, ~ dom x -> riscv_state_MEM8 (riscv_next ms) x = riscv_state_MEM8 ms x).
Proof.
  intros Hr (Hsup & Hb & Hmo & Hacc & Hal).
  pose proof Hr as (Hok & Hg & Hpc & Hm).
  pose proof Hok as Hok'. apply riscv_ok_iff in Hok' as (Hs & Hpal).
  assert (Hg' : aregs A = aregs (obs ms)) by exact (eq_sym Hg).
  destruct (step_thm ms i Hsup Hs Hpal (bytes_at_intro dom ms A i Hr Hb) (mem_ok_regs i A (obs ms) Hg' Hmo))
    as (s' & Hn & Hs' & Ho).
  unfold riscv_next. rewrite Hn. cbn [THE].
  destruct (aexec_cong dom i (obs ms) A Hg (eq_trans Hpc eq_refl) (fun a Ha => Hm a Ha)
             (acc_ok_regs dom i A (obs ms) Hg' Hacc)) as (E1 & E2 & E3).
  split.
  - split; [|split; [|split]].
    + apply riscv_ok_iff. split; [exact Hs'|]. change (riscv_state_c_PC s' (riscv_state_procID s')) with (apc (obs s')).
      rewrite Ho, E2. exact Hal.
    + change (gregs s') with (aregs (obs s')). rewrite Ho. exact E1.
    + change (riscv_state_c_PC s' (riscv_state_procID s')) with (apc (obs s')). rewrite Ho. exact E2.
    + intros a Ha. change (riscv_state_MEM8 s') with (amem (obs s')). rewrite Ho. apply E3, Ha.
  - intros x Hx. change (riscv_state_MEM8 s') with (amem (obs s')). rewrite Ho.
    apply aexec_out with dom; [|exact Hx]. exact (acc_ok_regs dom i A (obs ms) Hg' Hacc).
Qed.

Fixpoint arun (A : astate) (l : list instruction) : astate :=
  match l with [] => A | i :: l' => arun (aexec i A) l' end.

Fixpoint run_ok (dom : word64 -> Prop) (A : astate) (l : list instruction) (PA : astate -> Prop) : Prop :=
  match l with
  | [] => True
  | [i] => step_pre dom A i
  | i :: l' => step_pre dom A i /\ PA (aexec i A) /\ run_ok dom (aexec i A) l' PA
  end.

Section Path.
Variable dom : word64 -> Prop.
Variable env : N -> riscv_state -> riscv_state.
Hypothesis Henv : interference_ok env (riscv_proj dom).

Lemma path_asserts (P Q : riscv_state -> Prop) (PA QA : astate -> Prop) :
  (forall ms A, rv_rel dom ms A -> PA A -> P ms) ->
  (forall ms A, rv_rel dom ms A -> QA A -> Q ms) ->
  forall l ms A (f : N -> N), l <> [] ->
  rv_rel dom ms A -> run_ok dom A l PA -> QA (arun A l) ->
  asserts (LENGTH l - 1) (fun k s => env (f k) (riscv_next s)) ms P Q.
Proof.
  intros HP HQ l; induction l as [|i l IH]; intros ms A f Hne Hr Hrun HQA; [congruence|].
  destruct l as [|i' l'].
  - cbn [LENGTH]. replace (SUC 0 - 1) with 0 by lia. unfold asserts; rewrite num_rec_0.
    cbn [run_ok] in Hrun. destruct (one_step dom ms A i Hr Hrun) as [Hr' _].
    apply HQ with (aexec i A); [apply rv_rel_env; assumption|exact HQA].
  - cbn [LENGTH] in *. replace (SUC (SUC (LENGTH l')) - 1) with (SUC (LENGTH l')) by lia.
    unfold asserts; rewrite num_rec_SUC; fold (asserts (LENGTH l') (fun k s => env (f k) (riscv_next s))).
    cbv zeta. destruct Hrun as (Hs & HPA & Hrun).
    destruct (one_step dom ms A i Hr Hs) as [Hr' _].
    pose proof (rv_rel_env dom env (f (SUC (LENGTH l'))) _ _ Henv Hr') as Hr''.
    set (ms' := env (f (SUC (LENGTH l'))) (riscv_next ms)) in *.
    split; [apply HP with (aexec i A); assumption|].
    replace (LENGTH l') with (LENGTH (i' :: l') - 1) by (cbn [LENGTH]; lia).
    apply IH with (aexec i A); [discriminate|exact Hr''|exact Hrun|exact HQA].
Qed.

Fixpoint run_ok2 (A : astate) (l : list instruction) : Prop :=
  match l with
  | [] => True
  | i :: l' => step_pre dom A i /\ run_ok2 (aexec i A) l'
  end.

Lemma run_ok_ok2 l A PA : run_ok dom A l PA -> run_ok2 A l.
Proof.
  revert A; induction l as [|i l IH]; intros A H; [exact Logic.I|].
  destruct l as [|i' l']; cbn [run_ok run_ok2] in *; [split; [exact H|exact Logic.I]|].
  destruct H as (H1 & _ & H3). split; [exact H1|]. apply IH, H3.
Qed.

Lemma path_asserts2 :
  forall l ms A (g : N -> N), rv_rel dom ms A -> run_ok2 A l ->
  asserts2 (LENGTH l) (fun k => env (g k)) riscv_next ms
    (fun ms1 ms2 => forall x, x NOTIN dom -> riscv_state_MEM8 ms1 x = riscv_state_MEM8 ms2 x).
Proof.
  intros l; induction l as [|i l IH]; intros ms A g Hr Hrun; [exact Logic.I|].
  cbn [LENGTH]. unfold asserts2; rewrite num_rec_SUC.
  fold (asserts2 (LENGTH l) (fun k => env (g k)) riscv_next).
  destruct Hrun as (Hs & Hrun). destruct (one_step dom ms A i Hr Hs) as [Hr' Hout].
  split.
  - intros x Hx. symmetry. apply Hout, Hx.
  - apply IH with (aexec i A); [apply rv_rel_env; assumption|exact Hrun].
Qed.

