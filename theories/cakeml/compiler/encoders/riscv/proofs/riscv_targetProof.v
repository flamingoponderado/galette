Ltac bit_hyps :=
  repeat match goal with H : word_bit ?k ?x = ?b |- context [word_bit ?k ?x] => rewrite H end.

Ltac bool_fin :=
  repeat match goal with |- context [word_bit ?k ?x] => destruct (word_bit k x) end; reflexivity.

