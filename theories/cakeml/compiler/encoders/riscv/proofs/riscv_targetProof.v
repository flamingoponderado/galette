Definition is_alu (i : instruction) : bool :=
  match i with
  | ArithI _ | ArithR _ | Shift _ | MulDiv _ => supported i
  | _ => false
  end.

Lemma alu_props i A : is_alu i = true ->
  supported i = true /\ apc (aexec i A) = word_add (apc A) (n2w 4) /\ amem (aexec i A) = amem A /\
  mem_ok i A /\ (forall dom, acc_ok dom i A).
Proof.
  destruct A as [g pc m]; intros H. inst_cases' i; cbn in H |- *; try discriminate H;
    (split; [reflexivity|split; [reflexivity|split; [reflexivity|split; [exact Logic.I|intros; exact Logic.I]]]]).
Qed.

Lemma riscv_enc_flat i : riscv_enc i = FLAT (MAP riscv_encode (riscv_ast i)).
Proof. reflexivity. Qed.

Lemma LENGTH_app_ {A} (l1 l2 : list A) : LENGTH (l1 ++ l2) = LENGTH l1 + LENGTH l2.
Proof. induction l1 as [|x l1 IH]; cbn [app LENGTH]; [lia|rewrite IH; lia]. Qed.

Lemma LENGTH_FLAT_encode l : LENGTH (FLAT (MAP riscv_encode l)) = 4 * LENGTH l.
Proof.
  induction l as [|i l IH]; [reflexivity|].
  cbn [MAP FLAT List.concat List.map]. rewrite LENGTH_app_, IH. cbn [LENGTH]. unfold riscv_encode; cbn [LENGTH]. lia.
Qed.

Lemma aligned_add4 (pc : word64) k : aligned 2 pc = true -> aligned 2 (word_add pc (n2w (4 * k))) = true.
Proof.
  intros H. assert (Ha : aligned 2 (n2w (4 * k) : word64)).
  { apply alignment.MOD_0_aligned. change (2 ** 2) with 4. rewrite N.mul_comm. apply N.Div0.mod_mul. }
  rewrite (proj1 (alignment.aligned_add_sub 2 pc (n2w (4 * k)) Ha)). exact H.
Qed.

Lemma alu_run_gen s1 i dom : aligned 2 s1.(pc) = true ->
  forall l k A, l <> [] -> forallb is_alu l = true ->
  bytes_in_memory (word_add s1.(pc) (n2w (4 * k))) (FLAT (MAP riscv_encode l)) s1.(mem) dom ->
  apc A = word_add s1.(pc) (n2w (4 * k)) -> amem A = s1.(mem) ->
  4 * k + 4 * LENGTH l <= LENGTH (riscv_enc i) ->
  run_ok dom A l (PA_of s1 i) /\ apc (arun A l) = word_add s1.(pc) (n2w (4 * (k + LENGTH l))) /\
  amem (arun A l) = s1.(mem).
Proof.
  intros Hal l; induction l as [|j l IH]; intros k A Hne Hall Hb Hpc Hm Hlen; [congruence|].
  cbn [forallb] in Hall. apply Bool.andb_true_iff in Hall as [Hj Hall].
  destruct (alu_props j A Hj) as (Hs & Hpc' & Hm' & Hmo & Hacc).
  cbn [MAP FLAT List.concat List.map] in Hb. apply bytes_in_memory_APPEND in Hb as [Hb1 Hb2].
  assert (Hpc2 : word_add (word_add s1.(pc) (n2w (4 * k))) (n2w (LENGTH (riscv_encode j))) =
                 word_add s1.(pc) (n2w (4 * (k + 1)))) by (rewrite add_n2w_add; f_equal; f_equal; unfold riscv_encode; cbn [LENGTH]; lia).
  rewrite Hpc2 in Hb2.
  assert (Hst : step_pre dom A j).
  { split; [exact Hs|split; [rewrite Hpc, Hm; exact Hb1|split; [exact Hmo|split; [apply Hacc|]]]].
    rewrite Hpc', Hpc, add_n2w_add. replace (4 * k + 4) with (4 * (k + 1)) by lia. apply aligned_add4, Hal. }
  destruct l as [|j' l'].
  - cbn [run_ok arun LENGTH]. split; [exact Hst|]. rewrite Hpc', Hm', Hpc, add_n2w_add.
    split; [f_equal; f_equal; lia|exact Hm].
  - destruct (IH (k + 1) (aexec j A) ltac:(discriminate) Hall Hb2) as (Hr & Hp & Hmm).
    + rewrite Hpc', Hpc, add_n2w_add. f_equal; f_equal; lia.
    + rewrite Hm'; exact Hm.
    + cbn [LENGTH] in *. lia.
    + cbn [run_ok arun LENGTH] in *. split; [split; [exact Hst|split; [|exact Hr]]|].
      * split; [rewrite Hm'; exact Hm|]. rewrite Hpc', Hpc, add_n2w_add.
        exists (k + 1). split; [f_equal; f_equal; change (2 ** 2) with 4; lia|].
        change (2 ** 2) with 4. cbn [LENGTH] in Hlen. lia.
      * split; [rewrite Hp; f_equal; f_equal; lia|exact Hmm].
Qed.

Lemma alu_run s1 i dom l A : aligned 2 s1.(pc) = true -> riscv_ast i = l -> l <> [] ->
  forallb is_alu l = true -> bytes_in_memory s1.(pc) (riscv_enc i) s1.(mem) dom ->
  apc A = s1.(pc) -> amem A = s1.(mem) ->
  run_ok dom A l (PA_of s1 i) /\ apc (arun A l) = word_add s1.(pc) (n2w (LENGTH (riscv_enc i))) /\
  amem (arun A l) = s1.(mem).
Proof.
  intros Hal Hl Hne Hall Hb Hpc Hm.
  rewrite riscv_enc_flat, Hl in Hb |- *. rewrite LENGTH_FLAT_encode.
  rewrite <- (add_n2w_0 s1.(pc)) in Hb, Hpc. change 0 with (4 * 0) in Hb, Hpc.
  destruct (alu_run_gen s1 i dom Hal l 0 A Hne Hall Hb Hpc Hm) as (H1 & H2 & H3).
  - rewrite riscv_enc_flat, Hl, LENGTH_FLAT_encode. lia.
  - split; [exact H1|split; [rewrite H2; f_equal; f_equal; lia|exact H3]].
Qed.

