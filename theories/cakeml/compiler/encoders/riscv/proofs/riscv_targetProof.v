  rewrite MIN_min. change (N.min 2 (dimindex 64 - 1)) with 2.
  rewrite BITS_0_mod. change (2 ^ N.succ 2) with 8.
  rewrite (N.mod_small (w2n p mod 8) (2 ^ 64)) by (pose proof (N.mod_lt (w2n p) 8); lia).
