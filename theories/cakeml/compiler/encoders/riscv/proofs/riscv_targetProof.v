Definition rv_rel (dom : word64 -> Prop) (ms : riscv_state) (A : astate) : Prop :=
  riscv_ok ms = true /\ gregs ms = aregs A /\
  riscv_state_c_PC ms (riscv_state_procID ms) = apc A /\
  (forall a, dom a -> riscv_state_MEM8 ms a = amem A a).

(** The memory accesses of an instruction lie in [dom]. *)
Definition acc_ok (dom : word64 -> Prop) (i : instruction) (A : astate) : Prop :=
  let r x := rreg (aregs A) x in
  let in_dom n rs1 (imm : word12) := forall k, k < n -> dom (word_add (word_add (r rs1) (sw2sw imm)) (n2w k)) in
  match i with
  | Load (LD (_, rs1, imm)) => in_dom 8 rs1 imm
  | Load (LWU (_, rs1, imm)) => in_dom 4 rs1 imm
  | Load (LHU (_, rs1, imm)) => in_dom 2 rs1 imm
  | Load (LBU (_, rs1, imm)) => in_dom 1 rs1 imm
  | Store (SD (rs1, _, imm)) => in_dom 8 rs1 imm
  | Store (SW (rs1, _, imm)) => in_dom 4 rs1 imm
  | Store (SH (rs1, _, imm)) => in_dom 2 rs1 imm
  | Store (SB (rs1, _, imm)) => in_dom 1 rs1 imm
  | _ => True
  end.

Definition step_pre (dom : word64 -> Prop) (A : astate) (i : instruction) : Prop :=
  supported i = true /\ bytes_in_memory (apc A) (riscv_encode i) (amem A) dom /\
  mem_ok i A /\ acc_ok dom i A /\ aligned 2 (apc (aexec i A)) = true.

Lemma riscv_proj_eq dom ms1 ms2 :
  riscv_proj dom ms1 = riscv_proj dom ms2 ->
  riscv_ok ms1 = riscv_ok ms2 /\ gregs ms1 = gregs ms2 /\
  riscv_state_c_PC ms1 (riscv_state_procID ms1) = riscv_state_c_PC ms2 (riscv_state_procID ms2) /\
  (forall a, dom a -> riscv_state_MEM8 ms1 a = riscv_state_MEM8 ms2 a).
Proof.
  unfold riscv_proj; intros H; injection H; intros Hpc Hm Hg He Hn Ha Hv.
  idtac.
  pose proof (proj1 (set_sep.fun2set_eq (riscv_state_MEM8 ms1) (riscv_state_MEM8 ms2) dom) Hm) as Hm'. unfold riscv_ok. rewrite Hpc, Hn, Ha, Hv, He. auto.
Qed.

Lemma rv_rel_env dom env i ms A :
  interference_ok env (riscv_proj dom) -> rv_rel dom ms A -> rv_rel dom (env i ms) A.
Proof.
  intros Hi (H1 & H2 & H3 & H4). destruct (riscv_proj_eq dom (env i ms) ms (Hi i ms)) as (E1 & E2 & E3 & E4).
  unfold rv_rel. rewrite E1, E2, E3. split; [exact H1|split; [exact H2|split; [exact H3|]]].
  intros a Ha; rewrite E4 by exact Ha; apply H4, Ha.
Qed.

Lemma aload_SUC' n m a :
  aload (SUC n) m a = word_or (word_lsl (aload n m (word_add a (n2w 1))) 8) (w2w (m a)).
Proof. apply aload_SUC. Qed.

Lemma aload_cong dom n m m' p :
  (forall k, k < n -> dom (word_add p (n2w k))) -> (forall a, dom a -> m a = m' a) ->
  aload n m p = aload n m' p.
Proof.
  revert p; induction n as [|n IH] using N.peano_ind; intros p Hd Hm; [reflexivity|].
  rewrite !aload_SUC. f_equal.
  - f_equal. apply IH; [|exact Hm]. intros k Hk. rewrite add_n2w_add. apply Hd. lia.
  - f_equal. apply Hm. rewrite <- (add_n2w_0 p). apply Hd. lia.
Qed.

Lemma astore_SUC n a d m :
  astore (SUC n) a d m = UPDATE a (w2w d) (astore n (word_add a (n2w 1)) (word_lsr d 8) m).
Proof. unfold astore; rewrite num_rec_SUC; reflexivity. Qed.

Lemma astore_cong dom n p d m m' x : (forall a, dom a -> m a = m' a) -> dom x ->
  astore n p d m x = astore n p d m' x.
Proof.
  revert p d; induction n as [|n IH] using N.peano_ind; intros p d Hm Hx; [apply Hm, Hx|].
  rewrite !astore_SUC. unfold UPDATE. destruct (decide (p = x)); [reflexivity|]. apply IH; assumption.
Qed.

Lemma astore_out dom n p d m x : (forall k, k < n -> dom (word_add p (n2w k))) -> ~ dom x ->
  astore n p d m x = m x.
Proof.
  revert p d; induction n as [|n IH] using N.peano_ind; intros p d Hd Hx; [reflexivity|].
  rewrite !astore_SUC. unfold UPDATE. destruct (decide (p = x)) as [<-|].
  - exfalso. apply Hx. rewrite <- (add_n2w_0 p). apply Hd. lia.
  - apply IH; [|exact Hx]. intros k Hk. rewrite add_n2w_add. apply Hd. lia.
Qed.

