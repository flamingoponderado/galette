Definition PA_of (s1 : asm_state 64) (i : asm.asm 64) (A : astate) : Prop :=
  amem A = s1.(mem) /\ apc A IN all_pcs (LENGTH (riscv_enc i)) s1.(pc) 2.

Definition QA_of (s2 : asm_state 64) (A : astate) : Prop :=
  apc A = s2.(pc) /\ (forall a, a IN s2.(mem_domain) -> amem A a = s2.(mem) a) /\
  (forall r, r < 32 -> ~ list.MEM r [0; 2; 3; 4; 31] -> aregs A (n2w r) = s2.(regs) r).

Definition A0_of (s1 : asm_state 64) (ms : riscv_state) : astate :=
  mk_astate (gregs ms) s1.(pc) s1.(mem).

Lemma enc_sim s1 i s2 ms (l : list instruction) :
  asm_step riscv_config s1 i s2 -> target_state_rel riscv_target s1 ms -> l <> [] ->
  run_ok s1.(mem_domain) (A0_of s1 ms) l (PA_of s1 i) -> QA_of s2 (arun (A0_of s1 ms) l) ->
  exists n, forall env,
    interference_ok env (proj riscv_target s1.(mem_domain)) ->
    let pcs := all_pcs (LENGTH (encode (config riscv_target) i)) s1.(pc) in
    asserts n (fun k s => env (n - k) (next riscv_target s)) ms
