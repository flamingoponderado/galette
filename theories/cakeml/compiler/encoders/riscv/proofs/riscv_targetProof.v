Definition enc_goal s1 i s2 ms : Prop :=
  exists n, forall env,
    interference_ok env (proj riscv_target s1.(mem_domain)) ->
    let pcs := all_pcs (LENGTH (encode (config riscv_target) i)) s1.(pc) in
    asserts n (fun k s => env (n - k) (next riscv_target s)) ms
      (fun ms' => state_ok riscv_target ms' /\
         (forall pc0, pc0 IN pcs 0 -> get_byte riscv_target ms' pc0 = get_byte riscv_target ms pc0) /\
         get_pc riscv_target ms' IN pcs (code_alignment (config riscv_target)))
      (fun ms' => target_state_rel riscv_target s2 ms') /\
    asserts2 (n + 1) (fun k => env (n + 1 - k)) (next riscv_target) ms
      (fun ms1 ms2 => forall x, x NOTIN s1.(mem_domain) ->
         get_byte riscv_target ms1 x = get_byte riscv_target ms2 x).

