Ltac decode_tac :=
  match goal with |- Decode ?w = _ =>
    let Ht := fresh "Ht" in
    eassert (Ht : boolify32 w = _);
    [ unfold boolify32; cbn [Encode Rtype Itype Stype SBtype Utype UJtype]; unfold opc; wbs; reflexivity
    | unfold Decode; rewrite Ht; clear Ht; cbv beta iota zeta delta [andb negb orb];
      repeat match goal with |- (if ?c then _ else _) = _ =>
        let H := fresh in
        assert (H : c = false)
          by (repeat match goal with |- context [if ?b then _ else _] => destruct b end; reflexivity);
        rewrite H; clear H; cbv beta iota end;
      cbv beta iota zeta delta [asImm12 asImm20 asSImm12]; repeat f_equal; wblast ]
  end.

