    try (exfalso; revert Hm; vm_compute; intros Hm; discriminate Hm); vm_compute; discriminate.
Qed.

Lemma rawReadData_bit p s j : j + 8 * w2n ((word_extract 2 0) p : word3) < 64 ->
  word_bit j (rawReadData p s) = word_bit (j mod 8) (riscv_state_MEM8 s (word_add p (n2w (j / 8)))).
Proof.
  intros Hj. pose proof (addr_split p) as Hp.
  remember (w2n ((word_extract 2 0) p : word3)) as al eqn:Hal.
  remember ((word_extract 63 3) p : word 61) as idx eqn:Hidx.
  remember (word_lsl (w2w idx : word64) 3) as b eqn:Hb.
  assert (Hr : word_add p (n2w (j / 8)) = word_add b (n2w (al + j / 8))) by (rewrite Hp, add_n2w_add; reflexivity).
  rewrite Hr. clear Hr.
  unfold rawReadData; cbv zeta. rewrite <- Hal, <- Hidx.
  destruct (bool_decide (al = 0)) eqn:E.
  - apply bool_decide_spec in E. rewrite E, N.add_0_l. rewrite MEM_bit by lia. rewrite <- Hb. reflexivity.
  - rewrite wb_extract, wb_asr. change (dimindex 64) with 64. change (dimindex 128) with 128.
    rewrite (wb_concat (MEM (word_add idx (n2w 1)) s) (MEM idx s)) by reflexivity.
    change (dimindex 128) with 128. change (dimindex 64) with 64.
    rewrite !N.add_0_r.
    repeat match goal with
    | |- context [N.ltb ?x ?y] => destruct (N.ltb_spec x y); try lia
    | |- context [N.leb ?x ?y] => destruct (N.leb_spec x y); try lia
    end. cbn [andb].
    rewrite MEM_bit by lia. rewrite <- Hb. f_equal.
    + apply N.Div0.mod_add.
    + f_equal. f_equal. f_equal. rewrite N.div_add by lia. lia.
Qed.

