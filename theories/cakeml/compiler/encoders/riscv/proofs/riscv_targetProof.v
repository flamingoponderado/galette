        try destruct b; try destruct sh; cbn [riscv_ast];
        repeat match goal with |- context [if ?c then _ else _] => destruct c end; discriminate.
    + destruct m; discriminate.
    + discriminate.
  - repeat match goal with |- context [if ?c then _ else _] => destruct c end; discriminate.
  - destruct ri; destruct c;
      repeat match goal with |- context [if ?c then _ else _] => destruct c end; discriminate.
  - repeat match goal with |- context [if ?c then _ else _] => destruct c end; discriminate.
  - discriminate.
  - discriminate.
