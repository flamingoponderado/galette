Lemma NextRISCV_shape s i :
  s_ok s -> bytes_at s (Encode i) -> word_bit 1 (Encode i) = true ->
  word_bit 0 (Encode i) = true -> Decode (Encode i) = i ->
  run_shape i (write'Skip (n2w 4) s) ->
  exists s', NextRISCV s = Some s' /\ s_ok s' /\ obs s' = aexec i (obs s).
Proof.
  intros (HV & HA & HN & HE) Hb H1 H0 Hd Hs. rewrite (NextRISCV_run s i) by assumption.
  unfold run_shape in Hs. change (obs (write'Skip (n2w 4) s)) with (obs s) in Hs.
  cbv zeta in Hs |- *.
  destruct Hs as [[Hr Hpc]|Hr]; rewrite Hr; clear Hr.
  all: unfold mem_set, set_gregs, write'Skip, NextFetch, PC, riscv.Skip, update_pc, write'NextFetch, write'PC.
  all: cbn [riscv_state_MEM8_fupd riscv_state_c_gpr_fupd riscv_state_c_Skip_fupd riscv_state_c_NextFetch_fupd
            riscv_state_c_PC_fupd riscv_state_c_NextFetch riscv_state_procID riscv_state_c_PC
            riscv_state_c_Skip riscv_state_exception].
  all: rewrite HE, bool_decide_refl; cbn [negb]; rewrite ?HN, !UPDATE_same.
  all: eexists; split; [reflexivity|].
  all: split.
  all: try (unfold s_ok, s_VM, s_Arch;
    cbn [riscv_state_MEM8_fupd riscv_state_c_gpr_fupd riscv_state_c_Skip_fupd riscv_state_c_NextFetch_fupd
         riscv_state_c_PC_fupd riscv_state_c_NextFetch riscv_state_procID riscv_state_c_PC
         riscv_state_c_Skip riscv_state_exception riscv_state_c_MCSR riscv_state_c_gpr riscv_state_MEM8];
    rewrite ?UPDATE_same; split; [exact HV|split; [exact HA|split; [first [reflexivity|assumption]|assumption]]]).
  all: match goal with |- _ = ?R => rewrite (astate_eta R) end.
  all: unfold obs at 1, gregs at 1.
  all: cbn [riscv_state_MEM8_fupd riscv_state_c_gpr_fupd riscv_state_c_Skip_fupd riscv_state_c_NextFetch_fupd
            riscv_state_c_PC_fupd riscv_state_c_NextFetch riscv_state_procID riscv_state_c_PC
            riscv_state_c_Skip riscv_state_exception riscv_state_c_MCSR riscv_state_c_gpr riscv_state_MEM8].
  all: rewrite ?UPDATE_same.
  - cbn in Hpc. rewrite Hpc. reflexivity.
  - reflexivity.
Qed.

