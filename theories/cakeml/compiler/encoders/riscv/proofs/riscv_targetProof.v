  end.

Lemma store_gen k p d s : k <= 3 -> aligned k p = true ->
  riscv_state_MEM8 (rawWriteData (p, d, 2 ^ k) s) = astore (2 ^ k) p d (riscv_state_MEM8 s).
Proof.
  intros Hk Hal. pose proof (aligned_low k p Hal Hk) as Hm.
  pose proof (w2n_lt ((word_extract 2 0) p : word3)) as Hlt. change (dimword 3) with 8 in Hlt.
  pose proof (addr_split p) as Hp.
  unfold rawWriteData; cbv zeta.
  remember (w2n ((word_extract 2 0) p : word3)) as al eqn:Hal'.
  remember ((word_extract 63 3) p : word 61) as idx eqn:Hidx.
  remember (word_lsl (w2w idx : word64) 3) as b eqn:Hb.
  assert (Hp' : p = word_add b (n2w al)) by (subst; apply addr_split).
  rewrite Hp'. clear Hp Hp' Hal Hal' Hidx.
  assert (Hk' : k < 4) by lia. clear Hk.
  apply functional_extensionality; intros x.
  idx_cases Hk' idtac; idx_cases Hlt idtac;
    try (exfalso; revert Hm; vm_compute; intros Hm; discriminate Hm);
    clear Hm;
    repeat match goal with
    | |- context [word_sub (word_lsl (@w2w ?x ?y (n2w 1)) ?e) (n2w 1)] =>
        eval_closed_word (word_sub (word_lsl (@w2w x y (n2w 1)) e) (n2w 1))
    end;
    repeat match goal with
    | |- context [bool_decide (?u = ?v)] => is_lit u; is_lit v;
        let c := eval vm_compute in (bool_decide (u = v)) in change (bool_decide (u = v)) with c
    | |- context [N.leb ?u ?v] => closedB (N.leb u v);
        let c := eval vm_compute in (N.leb u v) in change (N.leb u v) with c
    | |- context [word_len ?w] => change (word_len w) with 64
    end; cbv beta iota.
  all: match goal with |- context [astore ?n] => closedN n; let v := eval vm_compute in n in change n with v end.
  all: cbn [write'MEM riscv_state_MEM8 riscv_state_MEM8_fupd]; rewrite <- Hb.
  all: astore_unfold.
  all: destruct (N.lt_ge_cases (w2n (word_sub x b)) 8) as [Hn|Hf];
    [destruct (near_key b x Hn) as (t & Ht & ->); clear Hn;
     idx_cases Ht ltac:(upd_eval b;
       apply word_bit_ext; let i := fresh "i" in let Hi := fresh "Hi" in intros i Hi;
       rewrite !wb_fcp by exact Hi; change (dimindex 8) with 8 in Hi;
       idx_cases Hi ltac:(wbs; mem_bits Hb; wbs; reflexivity))
    |upd_eval b;
     repeat (rewrite UPDATE_ne by (first [apply key_ne0; lia | apply key_ne; [lia | vm_compute; reflexivity]]));
     reflexivity].
Qed.

