(** ** One step of the RISC-V model (Galette-only)

    The registers, program counter and memory of a state, and the effect
    of executing one (supported) instruction on them. *)

Definition rreg (g : word5 -> word64) (r : word5) : word64 :=
  if bool_decide (r = n2w 0) then n2w 0 else g r.

Definition wreg (r : word5) (v : word64) (g : word5 -> word64) : word5 -> word64 :=
  if bool_decide (r = n2w 0) then g else UPDATE r v g.

Definition gregs (s : riscv_state) : word5 -> word64 :=
  riscv_state_c_gpr s (riscv_state_procID s).

Definition set_gregs (g : word5 -> word64) (s : riscv_state) : riscv_state :=
  riscv_state_c_gpr_fupd (fun _ => UPDATE (riscv_state_procID s) g (riscv_state_c_gpr s)) s.

Lemma GPR_rreg r s : GPR r s = rreg (gregs s) r.
Proof. reflexivity. Qed.

Lemma set_gregs_same s : set_gregs (gregs s) s = s.
Proof.
  destruct s; unfold set_gregs, gregs, riscv_state_c_gpr_fupd; cbn; f_equal.
  apply functional_extensionality; intros x; unfold UPDATE.
  destruct (decide (riscv_state_procID = x)) as [->|]; reflexivity.
Qed.

Lemma write'GPR_set v r s : write'GPR (v, r) s = set_gregs (wreg r v (gregs s)) s.
Proof.
  unfold write'GPR, wreg. destruct (bool_decide (r = n2w 0)); cbn [negb].
  - symmetry; apply set_gregs_same.
  - reflexivity.
Qed.

