(** Little-endian loads and stores of [n] bytes, recursing as
    [asmSem]'s [read_mem_word] and [write_mem_word]. *)
Definition aload (n : N) (m : word64 -> word8) : word64 -> word64 :=
  num_rec (fun _ => n2w 0)
    (fun _ r a => word_or (word_lsl (r (word_add a (n2w 1))) 8) (w2w (m a))) n.

Definition astore (n : N) : word64 -> word64 -> (word64 -> word8) -> word64 -> word8 :=
  num_rec (fun _ _ m => m)
    (fun _ r a d m => UPDATE a (w2w d) (r (word_add a (n2w 1)) (word_lsr d 8) m)) n.

Record astate := mk_astate { aregs : word5 -> word64; apc : word64; amem : word64 -> word8 }.

Definition obs (s : riscv_state) : astate :=
  mk_astate (gregs s) (riscv_state_c_PC s (riscv_state_procID s)) (riscv_state_MEM8 s).

Definition aexec (i : instruction) (A : astate) : astate :=
  let g := aregs A in let pc := apc A in let m := amem A in
  let r x := rreg g x in
  let alu rd v := mk_astate (wreg rd v g) (word_add pc (n2w 4)) m in
  let br (c : bool) (off : word12) :=
    mk_astate g (if c then word_add pc (word_lsl (sw2sw off : word64) 1) else word_add pc (n2w 4)) m in
  let st n rs1 rs2 (imm : word12) :=
    mk_astate g (word_add pc (n2w 4)) (astore n (word_add (r rs1) (sw2sw imm)) (r rs2) m) in
  match i with
  | ArithI (ADDI (rd, rs1, imm)) => alu rd (word_add (r rs1) (sw2sw imm))
  | ArithI (ORI (rd, rs1, imm)) => alu rd (word_or (r rs1) (sw2sw imm))
  | ArithI (XORI (rd, rs1, imm)) => alu rd (word_xor (r rs1) (sw2sw imm))
  | ArithI (ANDI (rd, rs1, imm)) => alu rd (word_and (r rs1) (sw2sw imm))
  | ArithI (LUI (rd, imm)) => alu rd (sw2sw (word_concat imm (n2w 0 : word12) : word32))
  | ArithI (AUIPC (rd, imm)) => alu rd (word_add pc (sw2sw (word_concat imm (n2w 0 : word12) : word32)))
  | Shift (SLLI (rd, rs1, imm)) => alu rd (word_lsl (r rs1) (w2n imm))
  | Shift (SRLI (rd, rs1, imm)) => alu rd (word_lsr (r rs1) (w2n imm))
  | Shift (SRAI (rd, rs1, imm)) => alu rd (word_asr (r rs1) (w2n imm))
  | Shift (SLL (rd, rs1, rs2)) => alu rd (word_lsl_bv (r rs1) (w2w (word_extract 5 0 (r rs2) : word6)))
  | Shift (SRL (rd, rs1, rs2)) => alu rd (word_lsr_bv (r rs1) (w2w (word_extract 5 0 (r rs2) : word6)))
  | Shift (SRA (rd, rs1, rs2)) => alu rd (word_asr_bv (r rs1) (w2w (word_extract 5 0 (r rs2) : word6)))
  | ArithR (ADD (rd, rs1, rs2)) => alu rd (word_add (r rs1) (r rs2))
  | ArithR (SUB (rd, rs1, rs2)) => alu rd (word_sub (r rs1) (r rs2))
  | ArithR (AND (rd, rs1, rs2)) => alu rd (word_and (r rs1) (r rs2))
  | ArithR (OR (rd, rs1, rs2)) => alu rd (word_or (r rs1) (r rs2))
  | ArithR (XOR (rd, rs1, rs2)) => alu rd (word_xor (r rs1) (r rs2))
  | ArithR (SLTU (rd, rs1, rs2)) => alu rd (v2w [word_lo (r rs1) (r rs2)])
  | MulDiv (MUL (rd, rs1, rs2)) => alu rd (word_mul (r rs1) (r rs2))
  | MulDiv (MULHU (rd, rs1, rs2)) =>
      alu rd (word_extract 127 64 (word_mul (w2w (r rs1) : word 128) (w2w (r rs2))) : word64)
  | MulDiv (riscv.DIV (rd, rs1, rs2)) =>
      alu rd (if bool_decide (r rs2 = n2w 0) then sw2sw (n2w 1 : word1) else word_quot (r rs1) (r rs2))
  | Load (LD (rd, rs1, imm)) => alu rd (aload 8 m (word_add (r rs1) (sw2sw imm)))
  | Load (LWU (rd, rs1, imm)) => alu rd (aload 4 m (word_add (r rs1) (sw2sw imm)))
  | Load (LHU (rd, rs1, imm)) => alu rd (aload 2 m (word_add (r rs1) (sw2sw imm)))
  | Load (LBU (rd, rs1, imm)) => alu rd (aload 1 m (word_add (r rs1) (sw2sw imm)))
  | Store (SD (rs1, rs2, imm)) => st 8 rs1 rs2 imm
  | Store (SW (rs1, rs2, imm)) => st 4 rs1 rs2 imm
  | Store (SH (rs1, rs2, imm)) => st 2 rs1 rs2 imm
  | Store (SB (rs1, rs2, imm)) => st 1 rs1 rs2 imm
  | Branch (JAL (rd, imm)) =>
      mk_astate (wreg rd (word_add pc (n2w 4)) g) (word_add pc (word_lsl (sw2sw imm : word64) 1)) m
  | Branch (JALR (rd, rs1, imm)) =>
      mk_astate (wreg rd (word_add pc (n2w 4)) g)
        (word_and (word_add (r rs1) (sw2sw imm)) (sw2sw (n2w 2 : word2))) m
  | Branch (BEQ (rs1, rs2, off)) => br (bool_decide (r rs1 = r rs2)) off
  | Branch (BNE (rs1, rs2, off)) => br (negb (bool_decide (r rs1 = r rs2))) off
  | Branch (BLT (rs1, rs2, off)) => br (word_lt (r rs1) (r rs2)) off
  | Branch (BLTU (rs1, rs2, off)) => br (word_lo (r rs1) (r rs2)) off
  | Branch (BGE (rs1, rs2, off)) => br (word_ge (r rs1) (r rs2)) off
  | Branch (BGEU (rs1, rs2, off)) => br (word_hs (r rs1) (r rs2)) off
  | _ => A
  end.

(** Alignment of the memory accesses. *)
Definition mem_ok (i : instruction) (A : astate) : Prop :=
  let r x := rreg (aregs A) x in
  match i with
  | Load (LD (_, rs1, imm)) => aligned 3 (word_add (r rs1) (sw2sw imm))
  | Load (LWU (_, rs1, imm)) => aligned 2 (word_add (r rs1) (sw2sw imm))
  | Load (LHU (_, rs1, imm)) => aligned 1 (word_add (r rs1) (sw2sw imm))
  | Store (SD (rs1, _, imm)) => aligned 3 (word_add (r rs1) (sw2sw imm))
  | Store (SW (rs1, _, imm)) => aligned 2 (word_add (r rs1) (sw2sw imm))
  | Store (SH (rs1, _, imm)) => aligned 1 (word_add (r rs1) (sw2sw imm))
  | _ => True
  end.

Definition supported (i : instruction) : bool :=
  match i with
  | ArithI (ADDI _) | ArithI (ORI _) | ArithI (XORI _) | ArithI (ANDI _)
  | ArithI (LUI _) | ArithI (AUIPC _)
  | Shift (SLLI _) | Shift (SRLI _) | Shift (SRAI _)
  | Shift (SLL _) | Shift (SRL _) | Shift (SRA _)
  | ArithR (ADD _) | ArithR (SUB _) | ArithR (AND _) | ArithR (OR _)
  | ArithR (XOR _) | ArithR (SLTU _)
  | MulDiv (MUL _) | MulDiv (MULHU _) | MulDiv (riscv.DIV _)
  | Load (LD _) | Load (LWU _) | Load (LHU _) | Load (LBU _)
  | Store (SD _) | Store (SW _) | Store (SH _) | Store (SB _)
  | Branch (JAL _) | Branch (JALR _) | Branch (BEQ _) | Branch (BNE _)
  | Branch (BLT _) | Branch (BLTU _) | Branch (BGE _) | Branch (BGEU _) => true
  | _ => false
  end.

