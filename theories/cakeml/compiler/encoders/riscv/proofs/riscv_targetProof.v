(** * CakeML [riscv_targetProof]: [encoder_correct] for RISC-V

    Port of [cakeml/compiler/encoders/riscv/proofs/riscv_targetProofScript.sml].

    HOL proves the theorem with the step evaluator ([riscv_stepLib]),
    bit-blasting ([blastLib]) and per-case tactics generated in ML.  Here
    the proof is structured by Galette-only lemmas:

    - a bit-blasting tactic [wblast] for concrete bit indices;
    - [Decode (Encode i) = i] for the 37 RISC-V instructions used by the
      encoder ([Decode_ADDI] ...);
    - the effect of one [NextRISCV] step on the registers, program counter
      and memory, as an abstract function [aexec] ([step_thm]), including
      the byte-level meaning of [rawReadData]/[rawWriteData] for aligned
      accesses;
    - a simulation lemma along a path of RISC-V instructions ([enc_sim]),
      which reduces [encoder_correct]'s obligation for an ASM instruction
      to a computation on abstract states; and one lemma per ASM
      instruction ([sim_skip], [sim_const], ..., [sim_jc_imm]).

    Not ported: the ML values [lem11] and [lem12] (statements generated by
    [asmLib.mk_blast_thm], i.e. by bit-blasting in ML), the rewrite lists
    [encode_rwts], [enc_rwts], [enc_ok_rwts] and the tactic helper
    [print_tac] (ML values that are not theorems).  HOL's [riscv_encoding]
    is an ML value proved with [Q.prove]; its statement after HOL's
    [SIMP_RULE] is ported. *)

