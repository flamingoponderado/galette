Lemma add_n2w_inj (b : word64) j t : j < 2 ^ 64 -> t < 2 ^ 64 ->
  word_add b (n2w j) = word_add b (n2w t) <-> j = t.
Proof.
  intros Hj Ht. rewrite lemmas.WORD_EQ_ADD_LCANCEL. split; [|intros ->; reflexivity].
  intros H. apply (f_equal w2n) in H. rewrite !w2n_n2w in H. change (dimword 64) with (2 ^ 64) in H.
  rewrite !N.mod_small in H by assumption. exact H.
Qed.

Lemma UPDATE_add_add (b : word64) j t (v : word8) f : j < 2 ^ 64 -> t < 2 ^ 64 ->
  UPDATE (word_add b (n2w j)) v f (word_add b (n2w t)) = if j =? t then v else f (word_add b (n2w t)).
Proof.
  intros Hj Ht. unfold UPDATE. destruct (decide _) as [E|E]; rewrite add_n2w_inj in E by assumption;
  destruct (N.eqb_spec j t); congruence.
Qed.

Lemma UPDATE_b_add (b : word64) t (v : word8) f : t < 2 ^ 64 ->
  UPDATE b v f (word_add b (n2w t)) = if 0 =? t then v else f (word_add b (n2w t)).
