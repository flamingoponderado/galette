Lemma concat_bytes (w : word32) :
  (word_concat ((word_extract 31 24) w : word8) (word_concat ((word_extract 23 16) w : word8)
     (word_concat ((word_extract 15 8) w : word8) ((word_extract 7 0) w : word8) : word16) : word 24) : word32) = w.
Proof. wblast. Qed.

Definition bytes_at (s : riscv_state) (w : word32) : Prop :=
  let pc := riscv_state_c_PC s (riscv_state_procID s) in
  riscv_state_MEM8 s pc = (word_extract 7 0) w /\
  riscv_state_MEM8 s (word_add pc (n2w 1)) = (word_extract 15 8) w /\
  riscv_state_MEM8 s (word_add pc (n2w 2)) = (word_extract 23 16) w /\
  riscv_state_MEM8 s (word_add pc (n2w 3)) = (word_extract 31 24) w.

Lemma Fetch_word s w :
  s_VM s = n2w 0 -> bytes_at s w -> word_bit 1 w = true -> word_bit 0 w = true ->
  riscv_step.Fetch s = (Word w, write'Skip (n2w 4) s).
Proof.
  intros HV (H0 & H1 & H2 & H3) Hb1 Hb0.
  unfold riscv_step.Fetch, PC. rewrite translateAddr_bare by exact HV. cbn [THE].
  unfold rawReadInst, boolify8. cbn [write'Skip riscv_state_c_Skip_fupd riscv_state_MEM8].
  rewrite H0, H1, H2, H3.
  rewrite (wb_extract w 7 0 1), (wb_extract w 7 0 0). cbn [N.add].
  change (1 <? dimindex 8) with true. change (0 <? dimindex 8) with true.
  change (1 <=? 7) with true. change (0 <=? 7) with true. rewrite Hb1, Hb0. cbn [andb].
  rewrite concat_bytes. reflexivity.
Qed.

Lemma aligned_wb {a : N} p (w : word a) i : aligned p w = true -> i < p -> word_bit i w = false.
Proof.
  intros H Hi. apply alignment.aligned_bits with (i := i) in H; [|exact Hi].
  rewrite word_bit_alt, fcp_index_testbit, H. apply Bool.andb_false_r.
Qed.

