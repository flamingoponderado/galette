(** The two shapes of the effect of [Run]: falling through to the next
    instruction, or transferring control. *)
Definition run_shape (i : instruction) (s : riscv_state) : Prop :=
  let A' := aexec i (obs s) in
  (Run i s = mem_set (amem A') (set_gregs (aregs A') s) /\
   apc A' = word_add (riscv_state_c_PC s (riscv_state_procID s)) (n2w 4)) \/
  Run i s = write'NextFetch (Some (BranchTo (apc A'))) (mem_set (amem A') (set_gregs (aregs A') s)).

Definition s_ok (s : riscv_state) : Prop :=
  s_VM s = n2w 0 /\ s_Arch s = n2w 2 /\
  riscv_state_c_NextFetch s (riscv_state_procID s) = None /\
  riscv_state_exception s = NoException.

Lemma riscv_ok_iff s :
  riscv_ok s = true <-> s_ok s /\ aligned 2 (riscv_state_c_PC s (riscv_state_procID s)) = true.
Proof.
  unfold riscv_ok, s_ok, s_VM, s_Arch. rewrite !Bool.andb_true_iff, !bool_decide_spec. tauto.
Qed.

Lemma NextRISCV_run s i :
  s_VM s = n2w 0 -> bytes_at s (Encode i) -> word_bit 1 (Encode i) = true ->
  word_bit 0 (Encode i) = true -> Decode (Encode i) = i ->
  NextRISCV s =
  (let s1 := Run i (write'Skip (n2w 4) s) in
   if negb (bool_decide (riscv_state_exception s1 = NoException)) then None
   else match NextFetch s1 with
        | None => update_pc (word_add (PC s1) (riscv.Skip s1)) s1
        | Some (BranchTo a) => update_pc a (write'NextFetch None s1)
        | _ => None
        end).
Proof.
  intros HV Hb H1 H0 Hd. unfold NextRISCV. rewrite (Fetch_word s (Encode i)) by assumption.
  cbn [DecodeAny]. rewrite Hd. reflexivity.
Qed.

Lemma bool_decide_refl {A} `{EqDecision A} (x : A) : bool_decide (x = x) = true.
Proof. apply bool_decide_spec; reflexivity. Qed.

Lemma astate_eta (A : astate) : A = mk_astate (aregs A) (apc A) (amem A).
