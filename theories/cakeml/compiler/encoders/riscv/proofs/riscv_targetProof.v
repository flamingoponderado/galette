  rewrite wb_or, wb_lsl, wb_lsr. change (dimindex 64) with 64.
  destruct (N.ltb_spec i 64); [|lia]. cbn [andb].
  destruct (N.ltb_spec (i + n) 64) as [Hin|Hin].
  - rewrite N.mod_small by exact Hin. destruct (N.leb_spec (64 - n) i); [lia|]. cbn [andb orb].
