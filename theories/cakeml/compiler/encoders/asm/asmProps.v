(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "write_mem_word_mem_eq" *)
Theorem write_mem_word_mem_eq : forall k (b w : word a) s (x : word a),
  ~ (write_mem_word b k w s).(failed) /\ x NOTIN s.(mem_domain) ->
  (write_mem_word b k w s).(mem) x = s.(mem) x.
Proof.
  intros k; induction k as [|k IH] using N.peano_ind; intros b w s x [Hf Hx]; [reflexivity|].
  rewrite (proj2 (write_mem_word_def b k w s)) in *; cbv zeta in *.
  set (s1 := write_mem_word _ k _ s) in *.
  unfold assert, upd_mem, set_failed, set_mem in *; cbn in *.
  destruct (classical_dec (b IN s1.(mem_domain))) as [Hb|Hb]; cbn in Hf;
    [|exfalso; apply Hf; reflexivity].
  unfold UPDATE; destruct (decide (b = x)) as [<-|Hne].
  - exfalso; apply Hx; unfold s1 in Hb; rewrite write_mem_word_mem_domain in Hb; exact Hb.
  - apply IH; split; [exact Hf|exact Hx].
Qed.

