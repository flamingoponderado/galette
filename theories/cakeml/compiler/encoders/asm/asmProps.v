(** ** Semantics is deterministic *)

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asm_deterministic" *)
Theorem asm_deterministic : forall {a} (c : asm_config a) i (s1 s2 s3 : asm_state a),
  asm_step c s1 i s2 /\ asm_step c s1 i s3 -> s2 = s3.
Proof.
  intros a c i s1 s2 s3 [(_ & _ & _ & _ & H2 & _) (_ & _ & _ & _ & H3 & _)].
  rewrite <- H2, <- H3; reflexivity.
Qed.

(** ** Well-formedness of encoding *)

Section Enc.
Context {a : N}.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "offset_monotonic_def" *)
Definition offset_monotonic (enc : asm.asm a -> list word8) (c : asm_config a)
    (a1 a2 : word a) (i1 i2 : asm.asm a) : Prop :=
  asm_ok i1 c /\ asm_ok i2 c ->
  ((n2w 0 <= a1)%w /\ (n2w 0 <= a2)%w /\ (a1 <= a2)%w -> LENGTH (enc i1) <= LENGTH (enc i2)) /\
  ((a1 < n2w 0)%w /\ (a2 < n2w 0)%w /\ (a2 <= a1)%w -> LENGTH (enc i1) <= LENGTH (enc i2)).

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "enc_ok_def" *)
Definition enc_ok (c : asm_config a) : Prop :=
  (* code alignment and length *)
  (2 ** code_alignment c = LENGTH (encode c (Inst Skip))) /\
  (forall w, (LENGTH (encode c w) MOD 2 ** code_alignment c = 0) /\
             LENGTH (encode c w) <> 0) /\
  (* label instantiation predictably affects length of code *)
  (forall w1 w2, offset_monotonic (encode c) c w1 w2 (Jump w1) (Jump w2)) /\
  (forall cmp r ri w1 w2,
     offset_monotonic (encode c) c w1 w2
       (JumpCmp cmp r ri w1) (JumpCmp cmp r ri w2)) /\
  (forall w1 w2, offset_monotonic (encode c) c w1 w2 (Call w1) (Call w2)) /\
  (forall w1 w2 r, offset_monotonic (encode c) c w1 w2 (Loc r w1) (Loc r w2)).

End Enc.

(** ** Targets *)

(** HOL's record [target], fields in HOL's order. *)
(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "target" *)
Record target (a : N) (B C : Type) : Type := mk_target {
  config : asm_config a;
  next : B -> B;
  get_pc : B -> word a;
  get_reg : B -> N -> word a;
  get_fp_reg : B -> N -> word64;
  get_byte : B -> word a -> word8;
  state_ok : B -> bool;
  proj : (word a -> Prop) -> B -> C
}.
Arguments mk_target {a B C} _ _ _ _ _ _ _ _.
Arguments config {a B C} _.
Arguments next {a B C} _ _.
Arguments get_pc {a B C} _ _.
Arguments get_reg {a B C} _ _ _.
Arguments get_fp_reg {a B C} _ _ _.
Arguments get_byte {a B C} _ _ _.
Arguments state_ok {a B C} _ _.
Arguments proj {a B C} _ _ _.

Section Targets.
Context {a : N} {B C : Type}.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "target_state_rel_def" *)
Definition target_state_rel (t : target a B C) (s : asm_state a) (ms : B) : Prop :=
  state_ok t ms /\ (get_pc t ms = s.(pc)) /\
  (forall ad, ad IN s.(mem_domain) -> get_byte t ms ad = s.(mem) ad) /\
  (forall i, i < reg_count (config t) /\ ~ MEM i (avoid_regs (config t)) ->
     get_reg t ms i = s.(regs) i) /\
  (forall i, i < fp_reg_count (config t) -> get_fp_reg t ms i = s.(fp_regs) i).

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "target_ok_def" *)
Definition target_ok (t : target a B C) : Prop :=
  enc_ok (config t) /\
  forall ms1 ms2 (s : asm_state a),
    proj t s.(mem_domain) ms1 = proj t s.(mem_domain) ms2 ->
    (target_state_rel t s ms1 <-> target_state_rel t s ms2) /\
    (state_ok t ms1 = state_ok t ms2) /\
    (get_pc t ms1 = get_pc t ms2) /\
    (forall ad, ad IN s.(mem_domain) -> get_byte t ms1 ad = get_byte t ms2 ad).

End Targets.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "interference_ok_def" *)
Definition interference_ok {B C : Type} (env : N -> B -> B) (proj : B -> C) : Prop :=
  forall (i : N) ms, proj (env i ms) = proj ms.

(** ** Program counters of an instruction *)

Section Pcs.
Context {a : N}.

(** [all_pcs n ad k]: the [2 ** k]-aligned offsets from [ad] below [n]. *)
Definition all_pcs (n : N) (ad : word a) (k : N) : word a -> Prop :=
  fun x => exists i, x = (ad + n2w (i * 2 ** k))%w /\ i * 2 ** k < n.

Lemma word_add_n2w_add (x : word a) p q :
  (x + n2w (p + q))%w = ((x + n2w p) + n2w q)%w.
Proof.
  apply word_eq_w2n; unfold word_add; rewrite !w2n_n2w.
  transitivity ((w2n x + p + q) MOD dimword a).
  - rewrite N.Div0.add_mod_idemp_r, N.add_assoc; reflexivity.
  - rewrite N.Div0.add_mod_idemp_r, N.Div0.add_mod_idemp_l.
    rewrite (N.add_comm (w2n x + p MOD dimword a) q), N.add_assoc, N.Div0.add_mod_idemp_r.
    f_equal; lia.
Qed.

Lemma word_add_n2w_0 (x : word a) : (x + n2w 0)%w = x.
Proof.
  apply word_eq_w2n; unfold word_add; rewrite !w2n_n2w, N.Div0.mod_0_l, N.add_0_r.
  apply N.mod_small, w2n_lt.
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "all_pcs_def" *)
Theorem all_pcs_def : forall n (ad : word a) k,
  all_pcs 0 ad k = EMPTY /\
  all_pcs (SUC n) ad k = ad INSERT all_pcs (SUC n - 2 ** k) (ad + n2w (2 ** k))%w k.
Proof.
  intros n ad k; split.
  - apply functional_extensionality; intros x; apply propositional_extensionality.
    unfold EMPTY, all_pcs; split; [intros (i & _ & H); lia|tauto].
  - apply functional_extensionality; intros x; apply propositional_extensionality.
    unfold pred_set.INSERT, pred_set.IN, all_pcs; split.
    + intros (i & -> & Hi).
      destruct i as [|i] using N.peano_ind.
      * left; rewrite N.mul_0_l; apply word_add_n2w_0.
      * right; exists i; split; [|lia].
        rewrite <- word_add_n2w_add; f_equal; f_equal; lia.
    + intros [->|(i & -> & Hi)].
      * exists 0; rewrite N.mul_0_l, word_add_n2w_0; split; [reflexivity|lia].
      * exists (SUC i); rewrite <- word_add_n2w_add; split; [f_equal; f_equal; lia|lia].
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "all_pcs_thm" *)
Theorem all_pcs_thm : forall n (ad : word a) k,
  all_pcs n ad k = (fun x => exists i, x = (ad + n2w (i * 2 ** k))%w /\ i * 2 ** k < n).
Proof. reflexivity. Qed.

End Pcs.

(** ** Assertions along a run *)

Section Asserts.
Context {B : Type}.

Definition asserts (n : N) (next : N -> B -> B) (ms : B) (P Q : B -> Prop) : Prop :=
  num_rec (fun ms => Q (next 0 ms))
    (fun n r ms => let ms' := next (SUC n) ms in P ms' /\ r ms') n ms.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts_def" *)
Theorem asserts_def : forall n next ms P Q,
  asserts 0 next ms P Q = Q (next 0 ms) /\
  asserts (SUC n) next ms P Q =
    (let ms' := next (SUC n) ms in P ms' /\ asserts n next ms' P Q).
Proof.
  intros; split; [reflexivity|]. unfold asserts; rewrite num_rec_SUC; reflexivity.
Qed.

Definition asserts2 (n : N) (fi : N -> B -> B) (fc : B -> B) (ms : B)
    (P : B -> B -> Prop) : Prop :=
  num_rec (fun _ => True)
    (fun m r ms => P ms (fc ms) /\ r (fi (SUC m) (fc ms))) n ms.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts2_def" *)
Theorem asserts2_def : forall n fi fc ms P,
  asserts2 n fi fc ms P =
  if bool_decide (n = 0) then True else
    P ms (fc ms) /\ asserts2 (n - 1) fi fc (fi n (fc ms)) P.
Proof.
  intros n fi fc ms P; destruct n as [|n] using N.peano_ind; [reflexivity|].
  unfold bool_decide; destruct (decide (N.succ n = 0)) as [H|_]; [lia|].
  unfold asserts2 at 1; rewrite num_rec_SUC.
  replace (N.succ n - 1) with n by lia; reflexivity.
Qed.

End Asserts.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts2_every" *)
Theorem asserts2_every : forall {B} (f g : B -> B) P n ms j,
  asserts2 n (fun k => f) g ms P /\ j < n ->
  P (FUNPOW (fun x => f (g x)) j ms) (g (FUNPOW (fun x => f (g x)) j ms)).
Proof.
  intros B f g P n; induction n as [|n IH] using N.peano_ind; intros ms j [H Hj]; [lia|].
  unfold asserts2 in H; rewrite num_rec_SUC in H; fold (asserts2 n (fun k => f) g (f (g ms)) P) in H.
  destruct H as [H0 H1].
  destruct j as [|j] using N.peano_ind; [exact H0|].
  rewrite !FUNPOW_SUC_r. apply IH; split; [exact H1|lia].
Qed.

(** ** The correctness property to be proved for each backend *)

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "encoder_correct_def" *)
Definition encoder_correct {a : N} {B C : Type} (t : target a B C) : Prop :=
  target_ok t /\
  forall s1 i s2 ms,
    asm_step (config t) s1 i s2 /\ target_state_rel t s1 ms ->
    exists n, forall (env : N -> B -> B),
      interference_ok env (proj t s1.(mem_domain)) ->
      let pcs := all_pcs (LENGTH (encode (config t) i)) s1.(pc) in
      asserts n (fun k s => env (n - k) (next t s)) ms
        (fun ms' => state_ok t ms' /\
           (forall pc0, pc0 IN pcs 0 -> get_byte t ms' pc0 = get_byte t ms pc0) /\
           get_pc t ms' IN pcs (code_alignment (config t)))
        (fun ms' => target_state_rel t s2 ms') /\
      asserts2 (n + 1) (fun k => env (n + 1 - k)) (next t) ms
        (fun ms1 ms2 => forall x, x NOTIN s1.(mem_domain) ->
           get_byte t ms1 x = get_byte t ms2 x).

(** ** Lemmas *)

Section Lemmas.
Context {a : N}.

Lemma bytes_in_memory_IN (m : word a -> word8) d : forall xs pc0 j,
  bytes_in_memory pc0 xs m d -> j < LENGTH xs -> (pc0 + n2w j)%w IN d.
Proof.
  intros xs; induction xs as [|x xs IH]; intros pc0 j H Hj; cbn [LENGTH] in Hj; [lia|].
  destruct H as (_ & Hd & H).
  destruct j as [|j] using N.peano_ind.
  - rewrite word_add_n2w_0; exact Hd.
  - replace (N.succ j) with (1 + j) by lia; rewrite word_add_n2w_add.
    apply IH; [exact H|lia].
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "bytes_in_memory_all_pcs" *)
Theorem bytes_in_memory_all_pcs : forall (m : word a -> word8) d k xs pc0,
  bytes_in_memory pc0 xs m d -> all_pcs (LENGTH xs) pc0 k SUBSET d.
Proof.
  intros m d k xs pc0 H x (i & -> & Hi).
  eapply bytes_in_memory_IN; eauto.
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "read_bytearray_IMP_bytes_in_memory" *)
Theorem read_bytearray_IMP_bytes_in_memory :
  forall (p : word a) n (m : word a -> option word8) ba m' md,
  n = LENGTH ba /\
  (forall k, k IN all_words p n -> k IN md /\ m k = Some (m' k)) /\
  read_bytearray p n m = Some ba ->
  bytes_in_memory p ba m' md.
Proof.
  intros p n m ba; revert p n; induction ba as [|b ba IH]; intros p n m' md (-> & Hk & Hr);
    [exact Logic.I|].
  cbn [LENGTH] in *.
  rewrite (proj2 (read_bytearray_def p m (LENGTH ba))) in Hr.
  destruct (m p) as [b'|] eqn:Ep; [|discriminate].
  destruct (read_bytearray (p + n2w 1)%w (LENGTH ba) m) as [bs|] eqn:Eb; [|discriminate].
  injection Hr as <- <-.
  assert (Hp : p IN all_words p (SUC (LENGTH bs))).
  { unfold pred_set.IN; rewrite (proj2 (all_words_def p (LENGTH bs))); left; reflexivity. }
  destruct (Hk p Hp) as [Hmd Hm]; rewrite Ep in Hm; injection Hm as ->.
  cbn [bytes_in_memory]; split; [reflexivity|split; [exact Hmd|]].
  apply (IH (p + n2w 1)%w (LENGTH bs) m' md); split; [reflexivity|split; [|exact Eb]].
  intros k' Hk'; apply Hk; unfold pred_set.IN in *; rewrite (proj2 (all_words_def p (LENGTH bs))).
  right; exact Hk'.
Qed.

End Lemmas.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "sym_target_state_rel" *)
Theorem sym_target_state_rel : forall {a B C} (t : target a B C) s ms,
  target_state_rel t s ms <->
  state_ok t ms /\ (s.(pc) = get_pc t ms) /\
  (forall ad, ad IN s.(mem_domain) -> s.(mem) ad = get_byte t ms ad) /\
  (forall i, i < reg_count (config t) /\ ~ MEM i (avoid_regs (config t)) ->
     s.(regs) i = get_reg t ms i) /\
  (forall i, i < fp_reg_count (config t) -> s.(fp_regs) i = get_fp_reg t ms i).
Proof.
  intros a B C t s ms; unfold target_state_rel; split;
    intros (H1 & H2 & H3 & H4 & H5); repeat split; auto;
    intros; symmetry; auto.
Qed.

Section AssertsLemmas.
Context {B : Type}.

Lemma FOLDR_app {X Y} (f : X -> Y -> Y) e l1 l2 :
  FOLDR f e (l1 ++ l2) = FOLDR f (FOLDR f e l2) l1.
Proof. induction l1 as [|x l1 IH]; cbn; [reflexivity|rewrite IH; reflexivity]. Qed.

Lemma COUNT_LIST_SUC n : COUNT_LIST (SUC n) = COUNT_LIST n ++ [n].
Proof.
  rewrite !COUNT_LIST_GENLIST, (proj2 (GENLIST_thm I n)), SNOC_app; reflexivity.
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts_IMP_FOLDR_COUNT_LIST" *)
Theorem asserts_IMP_FOLDR_COUNT_LIST : forall n (next : N -> B -> B) ms P Q,
  asserts n next ms P Q -> Q (FOLDR next (next n ms) (COUNT_LIST n)).
Proof.
  intros n; induction n as [|n IH] using N.peano_ind; intros next ms P Q H.
  - exact H.
  - rewrite (proj2 (asserts_def n next ms P Q)) in H; destruct H as [_ H].
    rewrite COUNT_LIST_SUC, FOLDR_app; cbn [FOLDR].
    exact (IH next _ P Q H).
Qed.

Lemma FOLDR_REVERSE_GENLIST_SUC (f : N -> B -> B) s m j :
  FOLDR f s (REVERSE (GENLIST (fun i => SUC m - i) (SUC j))) =
  FOLDR f (f (SUC m) s) (REVERSE (GENLIST (fun i => m - i) j)).
Proof.
  rewrite GENLIST_CONS_aux, (proj2 (REVERSE_DEF _ _)), FOLDR_app; cbn [FOLDR].
  replace (SUC m - 0) with (SUC m) by lia.
  replace (fun i => SUC m - SUC i) with (fun i => m - i)
    by (apply functional_extensionality; intros; lia).
  reflexivity.
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts_IMP_FOLDR_COUNT_LIST_LESS" *)
Theorem asserts_IMP_FOLDR_COUNT_LIST_LESS : forall k n (next : N -> B -> B) ms P Q,
  asserts n next ms P Q /\ k < n ->
  P (FOLDR next ms (REVERSE (GENLIST (fun i => n - i) (SUC k)))).
Proof.
  intros k; induction k as [|k IH] using N.peano_ind; intros n next ms P Q [H Hk];
    (destruct n as [|n] using N.peano_ind; [lia|]);
    rewrite (proj2 (asserts_def n next ms P Q)) in H; destruct H as [HP H];
    rewrite FOLDR_REVERSE_GENLIST_SUC.
  - exact HP.
  - apply (IH n next _ P Q); split; [exact H|lia].
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts_WEAKEN" *)
Theorem asserts_WEAKEN : forall n (next next' : N -> B -> B) s (P P' Q : B -> Prop),
  (forall k, k <= n ->
     next k = next' k /\
     (P (FOLDR next s (REVERSE (GENLIST (fun i => n - i) (SUC k)))) ->
      P' (FOLDR next s (REVERSE (GENLIST (fun i => n - i) (SUC k)))))) ->
  asserts n next s P Q -> asserts n next' s P' Q.
Proof.
  intros n; induction n as [|n IH] using N.peano_ind; intros next next' s P P' Q Hk H.
  - destruct (Hk 0 ltac:(lia)) as [E _]; cbn in *; unfold asserts in *; cbn in *.
    rewrite <- E; exact H.
  - rewrite (proj2 (asserts_def n next s P Q)) in H.
    rewrite (proj2 (asserts_def n next' s P' Q)); cbv zeta in *.
    destruct H as [HP H].
    destruct (Hk (SUC n) ltac:(lia)) as [E _]; rewrite <- E.
    split.
    + destruct (Hk 0 ltac:(lia)) as [_ HP'].
      rewrite FOLDR_REVERSE_GENLIST_SUC in HP'; exact (HP' HP).
    + apply (IH next next' _ P P' Q); [|exact H].
      intros k Hkn; destruct (Hk (SUC k) ltac:(lia)) as [_ HPk]; split;
        [exact (proj1 (Hk k ltac:(lia)))|].
      rewrite !FOLDR_REVERSE_GENLIST_SUC in HPk; exact HPk.
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts2_change_interfer" *)
Theorem asserts2_change_interfer : forall n (fi fi2 : N -> B -> B) fc ms P,
  asserts2 n fi fc ms P /\ (forall k, k <= n -> fi k = fi2 k) ->
  asserts2 n fi2 fc ms P.
Proof.
  intros n; induction n as [|n IH] using N.peano_ind; intros fi fi2 fc ms P [H Hk];
    [exact Logic.I|].
  unfold asserts2 in *; rewrite num_rec_SUC in *; destruct H as [HP H].
  split; [exact HP|]. rewrite <- (Hk (SUC n)) by lia.
  apply (IH fi fi2); split; [exact H|intros; apply Hk; lia].
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "asserts2_first" *)
Theorem asserts2_first : forall n (fi : N -> B -> B) fc ms P,
  1 <= n /\ asserts2 n fi fc ms P -> P ms (fc ms).
Proof.
  intros n fi fc ms P [Hn H]; destruct n as [|n] using N.peano_ind; [lia|].
  unfold asserts2 in H; rewrite num_rec_SUC in H; exact (proj1 H).
Qed.

End AssertsLemmas.

