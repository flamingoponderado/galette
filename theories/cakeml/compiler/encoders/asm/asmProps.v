(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "SND_read_mem_word_consts" *)
Theorem SND_read_mem_word_consts : forall n (ad : word a) s,
  (snd (read_mem_word ad n s)).(be) = s.(be) /\
  (snd (read_mem_word ad n s)).(lr) = s.(lr) /\
  (snd (read_mem_word ad n s)).(align) = s.(align) /\
  (snd (read_mem_word ad n s)).(mem_domain) = s.(mem_domain).
Proof.
  intros n; induction n as [|n IH] using N.peano_ind; intros ad s; [repeat split|].
  rewrite (proj2 (read_mem_word_def ad n s)).
  specialize (IH (if s.(be) then (ad - n2w 1)%w else (ad + n2w 1)%w) s).
  destruct (read_mem_word _ n s) as [w s1]; cbn in *; exact IH.
Qed.

(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "write_mem_word_consts" *)
Theorem write_mem_word_consts : forall n (ad : word a) w s,
