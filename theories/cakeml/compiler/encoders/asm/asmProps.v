Theorem mem_op_outside_mem_domain : forall m n (y : asm.addr a) s (x : word a),
  x NOTIN s.(mem_domain) /\ ~ (mem_op m n y s).(failed) ->
  (mem_op m n y s).(mem) x = s.(mem) x.
Proof.
  intros m n y s x [Hx Hf]; destruct m; cbn -[mem_load mem_store] in *;
    first
      [ unfold mem_load in *; cbv zeta in *;
        destruct (read_mem_word _ _ s) as [w s1] eqn:E; cbn -[read_mem_word];
        rewrite (read_mem_word_IMP_mem_eq _ _ _ _ _ E); reflexivity
      | unfold mem_store, assert, set_failed in *; cbv zeta in *;
        cbn -[write_mem_word] in *;
        apply write_mem_word_mem_eq; split; [|exact Hx];
        intro H; apply Hf; rewrite H, orb_true_r; reflexivity ].
Qed.

