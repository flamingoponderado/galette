(*! HOL "cakeml/compiler/encoders/asm/asmPropsScript.sml" "read_mem_word_IMP_mem_eq" *)
Theorem read_mem_word_IMP_mem_eq : forall (ad : word a) k s w s',
  read_mem_word ad k s = (w, s') -> s'.(mem) = s.(mem).
Proof.
  intros ad k; revert ad; induction k as [|k IH] using N.peano_ind; intros ad s w s' H.
  - injection H as _ <-; reflexivity.
  - rewrite (proj2 (read_mem_word_def ad k s)) in H.
    destruct (read_mem_word _ k s) as [w1 s1] eqn:E.
    injection H as _ <-; cbn; exact (IH _ s w1 s1 E).
Qed.

