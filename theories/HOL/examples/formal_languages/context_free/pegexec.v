(*! HOL "HOL/examples/formal-languages/context-free/pegexecScript.sml" "kont" *)
Inductive kont (A B C E : Type) : Type :=
| ksym : pegsym A B C E -> kont A B C E -> kont A B C E -> kont A B C E
| appf1 : (C -> C) -> kont A B C E -> kont A B C E
| appf2 : (C -> C -> C) -> kont A B C E -> kont A B C E
| dropErr : kont A B C E -> kont A B C E
| addErr : locs -> E -> kont A B C E -> kont A B C E
| cmpErrs : kont A B C E -> kont A B C E
| cmpEO : option (locs * E) -> kont A B C E -> kont A B C E
| returnTo : list (A * locs) -> list (option C) -> kont A B C E -> kont A B C E
| restoreEO : option (locs * E) -> kont A B C E -> kont A B C E
| poplist : (list C -> C) -> kont A B C E -> kont A B C E
| listsym : pegsym A B C E -> (list C -> C) -> kont A B C E -> kont A B C E
| done : kont A B C E
| failed : kont A B C E.
Arguments ksym {A B C E} _ _ _.
Arguments appf1 {A B C E} _ _.
Arguments appf2 {A B C E} _ _.
Arguments dropErr {A B C E} _.
Arguments addErr {A B C E} _ _ _.
