(** * HOL4 [pegexec]: an executable PEG interpreter

    Port of [HOL/examples/formal-languages/context-free/pegexecScript.sml].

    HOL defines the interpreter as a continuation machine: [coreloop G]
    iterates a one-step function on [evalcase] states with [OWHILE] until a
    [Result] is reached ([NONE] if never), and [peg_exec]/[applykont] read
    the final state ([Looped] if the loop does not terminate).  These HOL
    definitions are ported as they are ([coreloop_def], [peg_exec_def],
    [applykont_def]); they are not executable ([OWHILE] decides termination
    classically).  The step function is [coreloop_step] (HOL's lambda,
    named).  [OWHILE] is HOL's [While$OWHILE_def]
    (with [num] = [N]); it is not yet in [While.v] and is defined here,
    untagged ([FUNPOW] is [arithmetic]'s).

    ** Execution (Galette)

    [coreloop_acc lk G hlk s H] runs the machine from [s] until it reaches a
    [Result] or [Looped] state, by structural recursion on a proof
    [H : Acc (Rstep G) s] that it does so.  The proof is erased by
    extraction, which leaves a plain tail-recursive loop over
    [coreloop_step_exec] (the step function with one rule lookup per
    nonterminal instead of two, through a lookup function [lk] proved equal
    to [FLOOKUP (rules G)]; [coreloop_step_exec_eq]).  Proved:

    - [coreloop_acc_run]: for every [H], [coreloop_acc lk G hlk s H] is HOL's
      result ([run G s], i.e. [peg_exec]/[applykont]).
    - [run_Result_Acc]: whenever HOL's result is a [Result r], the [Acc]
      proof exists.  With HOL's [peg_eval_total] and [exec_correct]
      ([peg_exec_Acc]): for a well-formed grammar ([wfG]) the machine
      started on any expression of [Gexprs G] (or any [nt n f] with
      [n IN FDOM G.rules]) with HOL's initial continuations terminates.

    So no fuel bound is involved: for a well-formed grammar the executable
    interpreter computes exactly HOL's [peg_exec] on every input.

    Not ported: [peg_exec_thm], [applykont_thm], [peg_nt_thm] (equation
    lists generated by ML code whose exact shapes are not reproduced; the
    same equations are the untagged [run_*] lemmas used below). *)

