(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "Rtype_def" *)
Definition Rtype '((o, f3, rd, rs1, rs2, f7) : word7 * word3 * word5 * word5 * word5 * word7) : word32 :=
  f7 @@ (rs2 @@ (rs1 @@ (f3 @@ (rd @@ o : word12) : word 15) : word20) : word 25).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "R4type_def" *)
Definition R4type '((o, f3, rd, rs1, rs2, rs3, f2) : word7 * word3 * word5 * word5 * word5 * word5 * word2) : word32 :=
  rs3 @@ (f2 @@ (rs2 @@ (rs1 @@ (f3 @@ (rd @@ o : word12) : word 15) : word20) : word 25) : word 27).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "Itype_def" *)
Definition Itype '((o, f3, rd, rs1, imm) : word7 * word3 * word5 * word5 * word12) : word32 :=
  imm @@ (rs1 @@ (f3 @@ (rd @@ o : word12) : word 15) : word20).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "Stype_def" *)
Definition Stype '((o, f3, rs1, rs2, imm) : word7 * word3 * word5 * word5 * word12) : word32 :=
  ((11 >< 5) imm : word7) @@ (rs2 @@ (rs1 @@ (f3 @@ (((4 >< 0) imm : word5) @@ o : word12) : word 15) : word20) : word 25).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "SBtype_def" *)
Definition SBtype '((o, f3, rs1, rs2, imm) : word7 * word3 * word5 * word5 * word12) : word32 :=
  (if word_bit 11 imm then n2w 1 else n2w 0 : word1) @@ (((9 >< 4) imm : word6) @@ (rs2 @@ (rs1 @@ (f3 @@ (((3 >< 0) imm : word4) @@ ((if word_bit 10 imm then n2w 1 else n2w 0 : word1) @@ o : word8) : word12) : word 15) : word20) : word 25) : word 31).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "Utype_def" *)
Definition Utype '((o, rd, imm) : word7 * word5 * word20) : word32 :=
  imm @@ (rd @@ o : word12).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "UJtype_def" *)
Definition UJtype '((o, rd, imm) : word7 * word5 * word20) : word32 :=
  (if word_bit 19 imm then n2w 1 else n2w 0 : word1) @@ (((9 >< 0) imm : word 10) @@ ((if word_bit 10 imm then n2w 1 else n2w 0 : word1) @@ (((18 >< 11) imm : word8) @@ (rd @@ o : word12) : word20) : word21) : word 31).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "opc_def" *)
Definition opc (code : word8) : word7 :=
  ((4 >< 0) code : word5) @@ (n2w 3 : word2).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "amofunc_def" *)
Definition amofunc '((code, aq, rl) : word5 * word1 * word1) : word7 :=
  code @@ (aq @@ rl : word2).

(*! HOL "HOL/examples/l3-machine-code/riscv/model/riscvScript.sml" "Encode_def" *)
Definition Encode (i : instruction) : word32 :=
  match i with
  | Branch (BEQ (rs1, rs2, imm)) =>
      SBtype (opc (n2w 24), n2w 0, rs1, rs2, imm)
  | Branch (BNE (rs1, rs2, imm)) =>
      SBtype (opc (n2w 24), n2w 1, rs1, rs2, imm)
  | Branch (BLT (rs1, rs2, imm)) =>
      SBtype (opc (n2w 24), n2w 4, rs1, rs2, imm)
  | Branch (BGE (rs1, rs2, imm)) =>
      SBtype (opc (n2w 24), n2w 5, rs1, rs2, imm)
  | Branch (BLTU (rs1, rs2, imm)) =>
      SBtype (opc (n2w 24), n2w 6, rs1, rs2, imm)
  | Branch (BGEU (rs1, rs2, imm)) =>
      SBtype (opc (n2w 24), n2w 7, rs1, rs2, imm)
  | Branch (JALR (rd, rs1, imm)) =>
      Itype (opc (n2w 25), n2w 0, rd, rs1, imm)
  | Branch (JAL (rd, imm)) =>
      UJtype (opc (n2w 27), rd, imm)
  | ArithI (LUI (rd, imm)) =>
      Utype (opc (n2w 13), rd, imm)
  | ArithI (AUIPC (rd, imm)) =>
      Utype (opc (n2w 5), rd, imm)
  | ArithI (ADDI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 0, rd, rs1, imm)
  | Shift (SLLI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 1, rd, rs1, (n2w 0 : word6) @@ imm)
  | ArithI (SLTI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 2, rd, rs1, imm)
  | ArithI (SLTIU (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 3, rd, rs1, imm)
  | ArithI (XORI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 4, rd, rs1, imm)
  | Shift (SRLI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 5, rd, rs1, (n2w 0 : word6) @@ imm)
  | Shift (SRAI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 5, rd, rs1, (n2w 16 : word6) @@ imm)
  | ArithI (ORI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 6, rd, rs1, imm)
  | ArithI (ANDI (rd, rs1, imm)) =>
      Itype (opc (n2w 4), n2w 7, rd, rs1, imm)
  | ArithR (ADD (rd, rs1, rs2)) =>
      Rtype (opc (n2w 12), n2w 0, rd, rs1, rs2, n2w 0)
  | ArithR (SUB (rd, rs1, rs2)) =>
      Rtype (opc (n2w 12), n2w 0, rd, rs1, rs2, n2w 32)
  | Shift (SLL (rd, rs1, rs2)) =>
      Rtype (opc (n2w 12), n2w 1, rd, rs1, rs2, n2w 0)
  | ArithR (SLT (rd, rs1, rs2)) =>
      Rtype (opc (n2w 12), n2w 2, rd, rs1, rs2, n2w 0)
  | ArithR (SLTU (rd, rs1, rs2)) =>
      Rtype (opc (n2w 12), n2w 3, rd, rs1, rs2, n2w 0)
  | ArithR (XOR (rd, rs1, rs2)) =>
      Rtype (opc (n2w 12), n2w 4, rd, rs1, rs2, n2w 0)
  | Shift (SRL (rd, rs1, rs2)) =>
