(** * HOL4 L3 RISC-V model [riscv] (generated by L3)

    Port of [HOL/examples/l3-machine-code/riscv/model/riscvScript.sml], which
    is itself generated by L3 through the [Import] library
    ([HOL/examples/l3-machine-code/common/Import.sml]).  This file was
    produced mechanically from the L3 source terms; the translation is:

    - [Construct [(t, cs)]] (an algebraic datatype) is an [Inductive];
      [Record (t, fs)] is a Rocq [Record] whose fields carry the names of
      HOL's accessor constants [t_f] (e.g. [riscv_state_c_PC]).  HOL type
      names that are also constructor names ([ArithI], [Branch], [Load], ...)
      get the suffix [_ty]; constructors keep their HOL names.
    - [FTy n] / [F8] ... is [word n]; [PTy (a, b)] is [a * b]: an L3 tuple
      [a # b # c] is the Rocq tuple [a * b * c] (written and matched as
      [(x, y, z)] on both sides; only whole tuples are ever matched).
    - [Def (f, TP [x; y], e)] is [Definition f '((x, y) : ...) := e].
    - [LW (i, n)] is [n2w i : word n]; [EX (x, h, l, ty)] is
      [(h >< l) x : ty]; [CC [x; ...; y]] is [x @@ ... @@ y];
      [Bop (Bit, x, n)] is [word_bit n x]; [Mop (Cast F1, b)] for a boolean
      [b] is HOL's [v2w [b] : word1] (bitstring theory, not yet ported),
      written here as [(if b then n2w 1 else n2w 0 : word1)], its value.
      The notations are those of [word_scope].  HOL infers the widths of
      [@@] operands and of intermediate concatenations (the sums of the
      operand widths); Rocq cannot, so they are written as ascriptions.

    The L3 declaration forms [Construct], [Record] are not recognised by
    [scripts/check-hol-refs.py] (only [val f_def = Def ...] is), so the
    datatypes carry no [HOL] tags; each says which HOL type it is.

    Ported so far: all datatypes and records (including [riscv_state]), and
    the instruction encoder [Encode] with its helpers ([opc], [amofunc],
    [Rtype], [R4type], [Itype], [Stype], [SBtype], [Utype], [UJtype]), which
    is what CakeML's RISC-V encoder ([riscv_target]) uses.

    Not yet ported (still to do): the state monad helpers
    ([raise'exception], CSR/register accessors, [archBase], ...), memory and
    translation ([translateAddr], TLB), the [dfn'*] instruction semantics,
    [Run], [Fetch], [Decode], [DecodeRVC], [EncodeRVC], [CBtype], [Next],
    the string assembler/disassembler functions ([pRtype], ...), and the
    derived [riscv_step] theory ([NextRISCV]) used by [riscv_target]'s
    [riscv_next]. *)

